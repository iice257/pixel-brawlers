// BRICK portrait, authored in reference-grid coordinates (x 0..80 + OX), front / three-quarter view, not mirrored.
import { outlineSilhouette, mk, out, T, flat, edge, circle, stampT, putT, lineT } from './portrait_lib.mjs';
import { form } from '../blockin.mjs';

const SK = '12345', HR = 'abcd', TANK = 'efgh';
const strokes = (g, list, ch, only) => list.forEach(([x0, y0, x1, y1]) => lineT(g, x0, y0, x1, y1, ch, only));
const dots = (g, list, ch, only) => list.forEach(([x, y]) => putT(g, x, y, ch, only));
const row = (g, y, x0, x1, ch, only) => { for (let x = x0; x <= x1; x++) putT(g, x, y, ch, only); };

export function brickPortrait() {
  const g = mk();

  // ---- right arm (bare, far side)
  const armR = T([[56, 60], [62, 60], [70, 64], [76, 72], [80, 82], [81, 96], [56, 96], [59, 84], [57, 72]]);
  form(g, armR, SK, 2, { spread: 3 });
  flat(g, T([[60, 66], [66, 70], [70, 78], [72, 90], [66, 96], [62, 96], [63, 84], [61, 74]]), '4', '3');
  flat(g, T([[72, 70], [76, 72], [80, 82], [81, 96], [76, 96], [76, 84], [73, 76]]), '2', '34');
  strokes(g, [[62, 72, 70, 80], [66, 84, 74, 90]], '2', '34');
  stampT(g, 64, 66, ['5555', '555.', '55..']);
  edge(g, armR);

  // ---- tank top
  const tank = T([[8, 58], [10, 58], [18, 64], [30, 68], [42, 62], [44, 58], [50, 60], [58, 64], [60, 76], [62, 96], [8, 96]]);
  flat(g, tank, 'h');
  // grey folds: diagonal strokes and patches
  strokes(g, [[10, 70, 20, 74], [14, 78, 26, 82], [22, 72, 34, 76], [30, 80, 42, 84], [16, 86, 28, 90], [34, 88, 48, 92], [40, 72, 48, 76], [48, 80, 52, 86], [10, 71, 20, 75], [15, 79, 27, 83], [31, 81, 43, 85], [35, 89, 49, 93]], 'g', 'h');
  strokes(g, [[18, 70, 24, 72], [26, 78, 34, 80], [20, 84, 26, 86], [38, 74, 44, 76]], 'f', 'gh');
  strokes(g, [[12, 76, 18, 80], [24, 84, 30, 88], [38, 76, 44, 80], [46, 84, 50, 90]], 'f', 'gh');
  flat(g, T([[20, 66], [32, 70], [36, 76], [24, 74]]), 'g', 'h');
  flat(g, T([[34, 84], [46, 82], [50, 90], [40, 92]]), 'g', 'h');
  flat(g, T([[14, 88], [26, 86], [28, 94], [16, 94]]), 'g', 'h');
  // shaded right side of the tank (in the ref the far side is mid/dark grey)
  flat(g, T([[48, 62], [58, 64], [60, 76], [62, 96], [50, 96], [52, 80], [50, 70]]), 'g', 'h');
  flat(g, T([[54, 66], [58, 66], [60, 76], [61, 96], [56, 96], [56, 80], [54, 72]]), 'f', 'gh');
  flat(g, T([[58, 70], [60, 76], [61, 96], [59, 96], [58, 84]]), 'e', 'fg');
  // left side/armhole grey
  flat(g, T([[8, 70], [12, 70], [12, 96], [8, 96]]), 'g', 'h');
  edge(g, tank, 'O', { skip: (x, y) => y <= 58 || x <= 12 });

  // ---- left shoulder (bare, near side), over the tank strap
  const shL = T([[0, 66], [4, 61], [10, 60], [13, 68], [13, 96], [0, 96]]);
  form(g, shL, SK, 2, { spread: 3 });
  flat(g, T([[1, 70], [6, 66], [9, 72], [9, 90], [1, 92]]), '4', '3');
  stampT(g, 2, 74, ['55', '55', '5.']);
  strokes(g, [[10, 70, 11, 80], [8, 84, 9, 92]], '2', '34');
  edge(g, shL);
  strokes(g, [[13, 68, 13, 96]], 'O');

  // ---- neck / trapezius (bare), scooped neckline
  const neck = T([[13, 53], [40, 52], [40, 60], [44, 64], [44, 66], [36, 68], [26, 68], [18, 64], [14, 58]]);
  form(g, neck, SK, 2, { spread: 3 });
  flat(g, T([[22, 58], [34, 58], [38, 64], [28, 66], [22, 62]]), '3', '2');
  flat(g, T([[24, 60], [30, 60], [32, 64], [26, 65]]), '4', '3');
  stampT(g, 26, 61, ['55', '5.']);
  // neckline outline (thick, 2px where tank overlaps neck)
  strokes(g, [[10, 57, 18, 64], [11, 57, 19, 65], [18, 64, 26, 68], [19, 65, 27, 69], [26, 68, 36, 68], [27, 69, 37, 69], [36, 68, 44, 64], [37, 69, 44, 65]], 'O');
  // dark shadow band under the chin
  strokes(g, [[13, 52, 18, 55], [18, 55, 26, 57], [26, 57, 33, 56], [33, 56, 38, 53], [14, 53, 19, 56], [19, 56, 26, 58], [26, 58, 33, 57], [33, 57, 38, 54]], 'O');

  // ---- hair: spiky yellow mass
  const clumps = [[24, 10, 20, 9], [10, 14, 6, 10], [38, 14, 6, 11], [14, 6, 8, 5], [24, 4, 9, 4], [34, 6, 8, 5], [8, 20, 4, 7], [41, 20, 3, 8], [20, 8, 6, 5], [30, 10, 7, 6]];
  for (const [cx, cy, rx, ry] of clumps) form(g, T(circle(cx, cy, rx, ry, 22)), HR, 2, { spread: 2 });
  // spike tips
  for (const [x, h] of [[7, 5], [12, 1], [17, 0], [22, 1], [27, 0], [32, 1], [37, 3], [41, 8]]) form(g, T([[x - 3, 10], [x - 1, h + 2], [x, h], [x + 1, h + 2], [x + 3, 10]]), HR, 2, { spread: 1 });
  dots(g, [[9, 4], [11, 2], [15, 1], [19, 0], [25, 0], [29, 1], [33, 0], [36, 2], [39, 4], [41, 7], [43, 10], [44, 14], [5, 10], [5, 14], [4, 18], [43, 18], [44, 22]], 'c');
  dots(g, [[19, 0], [29, 1], [11, 2]], 'd');
  // fringe tufts hanging over the forehead, hairline shadow
  for (const [x0, x1, y] of [[13, 16, 15], [20, 23, 15], [27, 30, 15], [32, 36, 15], [14, 15, 16], [28, 29, 16], [34, 35, 16], [35, 36, 17], [36, 37, 18]]) row(g, y, x0, x1, 'b');
  for (const [x0, x1, y] of [[12, 36, 14]]) row(g, y, x0, x1, 'c');
  dots(g, [[31, 15], [32, 15], [33, 16], [34, 16], [35, 17]], 'a');
  // highlight strokes on the spike tops
  strokes(g, [[8, 8, 12, 5], [14, 4, 18, 3], [22, 2, 26, 2], [28, 3, 32, 4], [34, 5, 38, 7], [10, 12, 14, 9], [18, 7, 22, 6], [26, 6, 30, 7], [16, 11, 19, 9], [24, 9, 27, 10]], 'd', 'bc');
  dots(g, [[13, 4], [23, 2], [30, 4], [36, 6], [11, 8]], 'z');
  // dark roots / shadow between clumps
  strokes(g, [[7, 18, 10, 22], [40, 14, 41, 22], [38, 24, 38, 27], [6, 24, 8, 27], [20, 12, 22, 15], [26, 12, 28, 15]], 'a', 'bc');

  // ---- head: ears first, then face
  for (const [x0, x1, y0, y1] of [[4, 9, 28, 38], [38, 43, 28, 36]]) { for (let y = y0; y <= y1; y++) row(g, y, x0, x1, '3'); }
  stampT(g, 5, 30, ['22', '2.', '22']);
  stampT(g, 40, 30, ['22', '.2', '22']);
  const face = T([[12, 17], [36, 17], [37, 22], [38, 30], [39, 38], [39, 46], [38, 52], [34, 53], [18, 53], [15, 48], [12, 42], [10, 36], [9, 30], [9, 24], [10, 18]]);
  flat(g, face, '3');
  flat(g, T([[17, 20], [32, 20], [33, 38], [30, 44], [22, 45], [17, 42], [16, 32]]), '4', '3');
  // salmon shading: cheeks, temples, jaw
  flat(g, T([[9, 30], [14, 32], [15, 40], [18, 48], [16, 51], [12, 44], [10, 38]]), '2', '34');
  flat(g, T([[31, 36], [37, 32], [38, 44], [36, 52], [32, 48], [30, 42]]), '2', '34');
  flat(g, T([[30, 14], [36, 14], [37, 24], [34, 26], [31, 20]]), '3', '4');
  flat(g, T([[10, 22], [14, 22], [14, 28], [10, 30]]), '3', '4');
  flat(g, T([[20, 46], [32, 46], [32, 52], [20, 52]]), '3', '4');
  // highlights
  stampT(g, 16, 16, ['555555', '555555', '.5555.']);                      // forehead blob
  stampT(g, 22, 31, ['55', '55', '55', '55', '.5']);            // nose bridge
  stampT(g, 12, 33, ['55', '55']);                                         // cheek
  stampT(g, 33, 34, ['5', '5']);
  strokes(g, [[14, 40, 17, 47], [35, 38, 33, 46]], '2', '34');
  strokes(g, [[12, 26, 17, 26], [28, 26, 35, 26]], '2', '34');
  row(g, 31, 12, 16, '2', '34'); row(g, 31, 29, 33, '2', '34');                // eye bags
  strokes(g, [[19, 35, 18, 41], [28, 35, 29, 41], [14, 21, 14, 25], [34, 21, 34, 25]], '2', '34');
  dots(g, [[23, 49], [23, 50]], '2', '34');
  stampT(g, 31, 33, ['55', '55', '.5']);
  strokes(g, [[13, 45, 18, 52]], '1', '2');
  // eyes
  stampT(g, 12, 29, ['wyyw']);
  stampT(g, 29, 29, ['wyyw']);
  row(g, 28, 11, 17, '1', '234'); row(g, 28, 28, 34, '1', '234');                // lids
  row(g, 27, 12, 17, '2', '34'); row(g, 27, 28, 34, '2', '34');                 // brow shadow
  row(g, 30, 12, 16, '2', '34'); row(g, 30, 29, 33, '2', '34');
  // nose underside and nostrils
  row(g, 41, 19, 27, '2', '34');
  dots(g, [[20, 40], [21, 40], [26, 40], [27, 40]], '1', '234');
  // mouth + toothpick
  row(g, 43, 18, 30, '4', '2345');
  row(g, 44, 19, 29, '4', '23');
  row(g, 45, 20, 27, 'x');
  row(g, 46, 20, 26, '2', '34');
  strokes(g, [[22, 44, 15, 51], [23, 44, 16, 51]], 'r');
  strokes(g, [[21, 45, 16, 50]], 's');
  // stubble hint
  dots(g, [[14, 47], [16, 49], [18, 51], [22, 50], [25, 51], [28, 50], [31, 49], [33, 47], [35, 45], [13, 44], [36, 41]], '2', '34');

  outlineSilhouette(g);
  return g;
}
